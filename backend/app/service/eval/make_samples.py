def make_dev_docx(out_path: str):
    """python-docx 生成：Heading 层级 + 表格（表格序列化验证为 P1 独立成块）"""
    doc = DocxDocument()

    for kind, text in DEV_DOCX_PARAGRAPHS:
        if kind == "h1":
            doc.add_heading(text, level=1)
        elif kind == "h2":
            doc.add_heading(text, level=2)
        elif kind == "h3":
            doc.add_heading(text, level=3)
        else:
            doc.add_paragraph(text)

    doc.add_paragraph("环境规划表：")
    table = doc.add_table(rows=len(DEV_DOCX_TABLE), cols=len(DEV_DOCX_TABLE[0]))
    table.style = "Table Grid"
    for r, row in enumerate(DEV_DOCX_TABLE):
        for c, cell in enumerate(row):
            p = table.cell(r, c).paragraphs[0]
            p.text = cell
            for run in p.runs:
                run.font.size = Pt(9)

    doc.save(out_path)


