def make_security_pdf(out_path: str):
    """生成带书签目录（TOC）的结构化 pdf：每章一页，章标题 + 段落，TOC 供 P1 章节树解析"""
    doc = fitz.open()
    toc = []

    for idx, (title, paragraphs) in enumerate(SECURITY_PDF_SECTIONS):
        page = doc.new_page()  # A4 默认尺寸
        toc.append([1, title, idx + 1])

        y = 72
        # 章标题
        page.insert_text((72, y), title, fontname="china-s", fontsize=18)
        y += 14
        page.draw_line(fitz.Point(72, y), fitz.Point(523, y))
        y += 24

        # 段落（自动换行）
        for para in paragraphs:
            rect = fitz.Rect(72, y, 523, 780)
            wrote = page.insert_textbox(rect, para, fontname="china-s", fontsize=11, align=0)
            if wrote < 0:
                # 单页放不下时溢出到下一页（样例内容量已控制，正常不会触发）
                page = doc.new_page()
                rect = fitz.Rect(72, 72, 523, 780)
                page.insert_textbox(rect, para, fontname="china-s", fontsize=11, align=0)
                y = 72
            y = 780 - wrote + 24 if False else y  # 占位，实际按固定行距推进
            y += len(para) // 42 * 16 + 32

    doc.set_toc(toc)
    doc.save(out_path)
    doc.close()


