    wb = Workbook()
    header_font = Font(bold=True, color="FFFFFF")
    header_fill = PatternFill("solid", fgColor="4472C4")

    ws1 = wb.active
    ws1.title = "办公用品清单"
    ws1.append(SUPPLIES_HEADER)
    for row in SUPPLIES_ROWS:
        ws1.append(row)

    ws2 = wb.create_sheet("领用流程")
    ws2.append(PROCESS_HEADER)
    for row in PROCESS_ROWS:
        ws2.append(row)

    ws3 = wb.create_sheet("特殊物资审批")
    ws3.append(SPECIAL_HEADER)
    for row in SPECIAL_ROWS:
        ws3.append(row)

    for ws in (ws1, ws2, ws3):
        for cell in ws[1]:
            cell.font = header_font
            cell.fill = header_fill
        # 列宽自适应（粗略）
        for col_idx in range(1, ws.max_column + 1):
            max_len = max(len(str(ws.cell(r, col_idx).value or "")) for r in range(1, ws.max_row + 1))
            ws.column_dimensions[ws.cell(1, col_idx).column_letter].width = max_len * 1.6 + 4

    wb.save(out_path)


