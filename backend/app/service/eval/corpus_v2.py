def plan_docs(count: int = 60) -> list[dict]:
    """规划 count 份文档的（实体、主题、格式）三元组分配

    e_idx = i // 主题数（每实体整批跑完 10 个主题），t_idx = i % 主题数；
    fmt = FORMATS[(t_idx + e_idx) % 5] —— count=60 时每主题覆盖全部 5 种格式、
    每种格式恰 12 份、每实体每种格式 2 份（跨实体同主题文档构成 hard negatives）。
    """
    n_topics = len(TOPIC_BUILDERS)
    plans = []
    for i in range(count):
        e_idx = (i // n_topics) % len(ENTITIES)
        t_idx = i % n_topics
        plans.append({"ent": ENTITIES[e_idx], "t_idx": t_idx,
                      "fmt": FORMATS[(t_idx + e_idx) % len(FORMATS)]})
    return plans


def build_doc(doc_idx: int, ent: dict, t_idx: int, seed: int = SEED) -> DocSpec:
    """按全局文档序号派生独立随机源（seed*1000+doc_idx），任意 count 下前缀可复现"""
    rng = random.Random(seed * 1000 + doc_idx)
    return TOPIC_BUILDERS[t_idx](ent, rng)


def render_doc(spec: DocSpec, fmt: str, out_dir: str, ec: str) -> str:
    """按格式分发渲染；文件名 = 文档标题.扩展名（实体名+主题决定唯一性）"""
    path = os.path.join(out_dir, f"{spec.title}.{fmt}")
    if fmt == "pdf":
        render_pdf(spec, path)
    elif fmt == "docx":
        render_docx(spec, path)
    elif fmt == "xlsx":
        render_xlsx(spec, path, ec)
    elif fmt == "md":
        render_md(spec, path)
    else:
        render_txt(spec, path)
    return path


def _copy_v1_samples(out_dir: str) -> dict[str, str]:
    """将 v1 的 5 份经典样例（P0-P2 阶段基线语料）生成到同目录，凑齐 65 份底座"""
    from app.service.eval.make_samples import build_all as build_v1
    return build_v1(out_dir)


def build_all(out_dir: str = CORPUS_DIR, count: int = 60, seed: int = SEED,
              include_v1: bool = False) -> dict[str, str]:
    """生成 v2 评测语料并返回 {文件名: 绝对路径}

    默认 60 份 = 6 实体 × 10 主题；include_v1=True 时追加 v1 样例 5 份，
    合计 65 份，作为评测库扩容与评测集 v2（260 题 = 65 份 × 4 题/份）的语料底座。
    """
    os.makedirs(out_dir, exist_ok=True)
    outputs: dict[str, str] = {}
    for doc_idx, plan in enumerate(plan_docs(count)):
        ent = plan["ent"]
        spec = build_doc(doc_idx, ent, plan["t_idx"], seed)
        path = render_doc(spec, plan["fmt"], out_dir, ent["city"])
        outputs[os.path.basename(path)] = path
    if include_v1:
        outputs.update(_copy_v1_samples(out_dir))
    return outputs


