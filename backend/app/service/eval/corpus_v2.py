def render_pdf(spec: DocSpec, path: str):
    """pdf：每章一页 + 书签目录（供 P1 章节树解析）；首页页首含文档标题，末页附速查表"""
    doc = fitz.open()
    toc = []
    for idx, (heading, paragraphs) in enumerate(spec.sections):
        page = doc.new_page()
        toc.append([1, heading, len(toc) + 1])
        y = 72
        if idx == 0:
            page.insert_text((72, y), spec.title, fontname="china-s", fontsize=13)
            y += 20
        page.insert_text((72, y), heading, fontname="china-s", fontsize=16)
        y += 12
        page.draw_line(fitz.Point(72, y), fitz.Point(523, y))
        y += 26
        for para in paragraphs:
            page.insert_textbox(fitz.Rect(72, y, 523, 780), para,
                                fontname="china-s", fontsize=11, align=0)
            y += max(1, -(-len(para) // 42)) * 16 + 18
    # 速查表作为附录页（表格行以分隔文本呈现，保证表格事实可被检索）
    header, rows = spec.table
    page = doc.new_page()
    toc.append([1, "关键标准速查表", len(toc) + 1])
    page.insert_text((72, 72), "关键标准速查表", fontname="china-s", fontsize=16)
    y = 108
    for row in [list(header)] + [list(r) for r in rows]:
        line = " | ".join(str(c) for c in row)
        page.insert_textbox(fitz.Rect(72, y, 523, 780), line,
                            fontname="china-s", fontsize=10, align=0)
        y += max(1, -(-len(line) // 45)) * 14 + 6
    doc.set_toc(toc)
    doc.save(path)
    doc.close()


def render_docx(spec: DocSpec, path: str):
    """docx：h1=文档标题，h2=章标题，正文段落；文末附 Table Grid 速查表"""
    doc = DocxDocument()
    doc.add_heading(spec.title, level=1)
    for heading, paragraphs in spec.sections:
        doc.add_heading(heading, level=2)
        for para in paragraphs:
            doc.add_paragraph(para)
    doc.add_paragraph("关键标准速查表：")
    header, rows = spec.table
    table = doc.add_table(rows=len(rows) + 1, cols=len(header))
    table.style = "Table Grid"
    for r, row in enumerate([list(header)] + [list(x) for x in rows]):
        for c, cell in enumerate(row):
            p = table.cell(r, c).paragraphs[0]
            p.text = str(cell)
            for run in p.runs:
                run.font.size = Pt(9)
    doc.save(path)


def render_xlsx(spec: DocSpec, path: str, ec: str):
    """xlsx：Sheet1=关键标准速查表 + 主题附表；Sheet 名带城市名保证实体锚点，表头蓝底白字"""
    wb = Workbook()
    header_font = Font(bold=True, color="FFFFFF")
    header_fill = PatternFill("solid", fgColor="4472C4")
    all_sheets = [(f"{ec}关键标准速查表", spec.table[0], spec.table[1])] + list(spec.sheets)
    for s_idx, (name, header, rows) in enumerate(all_sheets):
        ws = wb.active if s_idx == 0 else wb.create_sheet()
        ws.title = name[:31]
        ws.append([str(c) for c in header])
        for row in rows:
            ws.append([str(c) for c in row])
        for cell in ws[1]:
            cell.font = header_font
            cell.fill = header_fill
        for col_idx in range(1, ws.max_column + 1):
            max_len = max(len(str(ws.cell(r, col_idx).value or ""))
                          for r in range(1, ws.max_row + 1))
            ws.column_dimensions[ws.cell(1, col_idx).column_letter].width = max_len * 1.6 + 4
    wb.save(path)


def render_txt(spec: DocSpec, path: str):
    """txt：章标题与段落连排成块、空行分章（提取时段落自带章标题上下文），速查表附于文末"""
    blocks = [spec.title]
    for heading, paragraphs in spec.sections:
        blocks.append("\n".join([heading] + list(paragraphs)))
    header, rows = spec.table
    table_lines = [" | ".join(str(c) for c in row)
                   for row in [list(header)] + [list(r) for r in rows]]
    blocks.append("\n".join(["关键标准速查表"] + table_lines))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n\n".join(blocks) + "\n")


def render_md(spec: DocSpec, path: str):
    """md：# 文档标题 + ## 章标题；速查表以 Markdown 表格呈现（提取时标题行并入首段）"""
    lines = [f"# {spec.title}"]
    for heading, paragraphs in spec.sections:
        lines.append("")
        lines.append(f"## {heading}")
        for para in paragraphs:
            lines.append("")
            lines.append(para)
    header, rows = spec.table
    lines.append("")
    lines.append("## 关键标准速查表")
    lines.append("")
    lines.append("| " + " | ".join(str(c) for c in header) + " |")
    lines.append("| " + " | ".join(["---"] * len(header)) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


