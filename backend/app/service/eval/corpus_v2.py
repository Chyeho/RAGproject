@dataclass
class DocSpec:
    """单份文档的结构化内容：同一份内容渲染为 5 种格式（事实保持一致）"""
    title: str                                    # 完整标题（即文件名主干）
    sections: list                                # [(章标题, [段落, ...])]
    table: tuple = None                           # 速查表 (header, rows)：docx 表格 & xlsx Sheet1
    sheets: list = field(default_factory=list)    # xlsx 附加 Sheet：[(名称, header, rows)]


def _pick(rng, seq):
    return rng.choice(seq)


